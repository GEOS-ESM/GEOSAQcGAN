#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""
plot_leadmean_global_and_regional_timeseries.py

Plot regional lead-time mean statistics for AQcGAN v2.2.0 aerosol forecasts.

This script reads the regional mean time-series files generated by
compute_leadmean_global_and_regional_timeseries_data_and_scales.py and creates
two-panel plots showing the regional mean truth versus prediction and the
corresponding RMSE as a function of forecast lead time. Fixed y-axis limits are
read from the plot scale metadata file to ensure consistent visualization across
all variables and regions.

Inputs:
    - /gpfsm/dnb06/projects/p271/aqcgan_products/v2_2_0/leadmean_global_and_regional_timeseries/{VARIABLE}_{REGION}_mean_timeseries.npz
    - /gpfsm/dnb06/projects/p271/aqcgan_products/v2_2_0/plot_metadata/leadmean_global_and_regional_timeseries_scales.npz

Outputs:
    - /gpfsm/dnb06/projects/p271/aqcgan_products/v2_2_0/leadmean_global_and_regional_timeseries/plots/{VARIABLE}_{REGION}_mean_timeseries.png

Usage examples:
    Interactive mode:
        python plot_leadmean_global_and_regional_timeseries.py

    Plot one variable and region:
        python plot_leadmean_global_and_regional_timeseries.py --variable SO4 --region asia

    List available variables and regions:
        python plot_leadmean_global_and_regional_timeseries.py --list

    Plot all variables and all regions (Recommended):
        python plot_leadmean_global_and_regional_timeseries.py --all
"""

import argparse
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np


VARIABLES = [
    "BCPHILIC", "BCPHOBIC",
    "OCPHILIC", "OCPHOBIC",
    "DU001", "DU002", "DU003", "DU004", "DU005",
    "NH4a",
    "NO3an1", "NO3an2", "NO3an3",
    "SO4",
    "SS001", "SS002", "SS003", "SS004", "SS005",
]

REGIONS = {
    "global": "lat -90 to 90, lon -180 to 180",
    "global_land": "global land only",
    "global_ocean": "global ocean only",
    "north_america": "lat 5 to 85, lon -170 to -50",
    "south_america": "lat -60 to 15, lon -90 to -30",
    "europe": "lat 35 to 72, lon -25 to 45",
    "africa": "lat -35 to 38, lon -20 to 55",
    "asia": "lat 0 to 80, lon 45 to 180",
    "australia": "lat -50 to 0, lon 110 to 180",
    "tropics": "lat -23.5 to 23.5, lon -180 to 180",
    "arctic": "lat 66.5 to 90, lon -180 to 180",
    "antarctic": "lat -90 to -66.5, lon -180 to 180",
}

DESCRIPTIONS = {
    "BCPHILIC": "Hydrophilic Black Carbon",
    "BCPHOBIC": "Hydrophobic Black Carbon",
    "OCPHILIC": "Hydrophilic Organic Carbon",
    "OCPHOBIC": "Hydrophobic Organic Carbon",
    "DU001": "Dust Mixing Ratio Bin 001",
    "DU002": "Dust Mixing Ratio Bin 002",
    "DU003": "Dust Mixing Ratio Bin 003",
    "DU004": "Dust Mixing Ratio Bin 004",
    "DU005": "Dust Mixing Ratio Bin 005",
    "NH4a": "Ammonium ion aerosol phase",
    "NO3an1": "Nitrate size bin 001",
    "NO3an2": "Nitrate size bin 002",
    "NO3an3": "Nitrate size bin 003",
    "SO4": "Sulphate aerosol",
    "SS001": "Sea Salt Mixing Ratio Bin 001",
    "SS002": "Sea Salt Mixing Ratio Bin 002",
    "SS003": "Sea Salt Mixing Ratio Bin 003",
    "SS004": "Sea Salt Mixing Ratio Bin 004",
    "SS005": "Sea Salt Mixing Ratio Bin 005",
}


def choose_from_list(options, prompt):
    text = input(prompt).strip()

    if text.isdigit():
        idx = int(text)
        if idx < 0 or idx >= len(options):
            raise ValueError(f"Index must be between 0 and {len(options) - 1}")
        return options[idx]

    if text not in options:
        raise ValueError(f"Unknown option: {text}")

    return text


def print_variable_menu():
    print("\nChoose variable by name or number:")
    for i, var in enumerate(VARIABLES):
        print(f"  {i:02d}: {var:8s}  {DESCRIPTIONS[var]}")


def print_region_menu():
    print("\nChoose region by name or number:")
    for i, (region, desc) in enumerate(REGIONS.items()):
        print(f"  {i:02d}: {region:15s}  {desc}")


def print_options():
    print_variable_menu()
    print_region_menu()


def get_scales(scale_file, variable, region):
    if not scale_file.exists():
        return None, None

    data = np.load(scale_file, allow_pickle=True)

    regions = [str(x) for x in data["regions"]]
    variables = [str(x) for x in data["variables"]]

    if region not in regions or variable not in variables:
        return None, None

    region_idx = regions.index(region)
    var_idx = variables.index(variable)

    mean_ylim = (
        float(data["main_ymin"][region_idx, var_idx]),
        float(data["main_ymax"][region_idx, var_idx]),
    )

    rmse_ylim = (
        0.0,
        float(data["rmse_ymax"][region_idx, var_idx]),
    )

    return mean_ylim, rmse_ylim


def padded_ylim(values, floor_zero=False):
    values = np.asarray(values, dtype=float)
    vmin = np.nanmin(values)
    vmax = np.nanmax(values)

    if np.isclose(vmin, vmax):
        pad = abs(vmax) * 0.05 if vmax != 0 else 1.0
    else:
        pad = 0.08 * (vmax - vmin)

    ymin = vmin - pad
    ymax = vmax + pad

    if floor_zero:
        ymin = 0.0

    return ymin, ymax


def plot_one(variable, region, indir, outdir, scale_file, show=False):
    infile = indir / f"{variable}_{region}_mean_timeseries.npz"

    if not infile.exists():
        print(f"Missing, skipping: {infile}")
        return

    data = np.load(infile, allow_pickle=True)

    leads = data["leads"]
    pred = data["pred_ts"]
    truth = data["truth_ts"]
    rmse = data["rmse_ts"]

    units = str(data["units"]) if "units" in data else "kg/kg"

    mean_ylim, rmse_ylim = get_scales(scale_file, variable, region)

    if mean_ylim is None:
        mean_ylim = padded_ylim(np.r_[truth, pred], floor_zero=False)

    if rmse_ylim is None:
        rmse_ylim = padded_ylim(rmse, floor_zero=True)

    description = DESCRIPTIONS.get(variable, variable)

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(18, 6))

    ax1.plot(leads, truth, marker="o", linewidth=2, label="Truth")
    ax1.plot(leads, pred, marker="o", linewidth=2, label="Prediction")
    ax1.set_xticks(np.arange(24, 241, 24))
    ax1.set_xlabel("Lead Time (hours)")
    ax1.set_ylabel(f"Regional Mean ({units})")
    ax1.set_ylim(*mean_ylim)
    ax1.set_title(f"{variable}: Truth vs Prediction")
    ax1.grid(alpha=0.3)
    ax1.legend()

    ax2.plot(leads, rmse, marker="o", linewidth=2, color="red", label="RMSE")
    ax2.set_xticks(np.arange(24, 241, 24))
    ax2.set_xlabel("Lead Time (hours)")
    ax2.set_ylabel(f"RMSE ({units})")
    ax2.set_ylim(*rmse_ylim)
    ax2.set_title(f"{variable}: RMSE")
    ax2.grid(alpha=0.3)
    ax2.legend()

    fig.suptitle(
        f"AQcGAN v2.2.0 Aerosol Forecast\n"
        f"{variable} ({description}) | Region: {region}",
        fontsize=15,
    )

    plt.tight_layout()

    outfile = outdir / f"{variable}_{region}_mean_timeseries.png"
    plt.savefig(outfile, dpi=300, bbox_inches="tight")

    print(f"Saved: {outfile}")

    if show:
        plt.show()

    plt.close(fig)


def main():
    parser = argparse.ArgumentParser(
        description="Plot AQcGAN regional mean time series and RMSE."
    )

    parser.add_argument("--variable", help="Variable name, e.g. BCPHILIC, SO4")
    parser.add_argument("--region", help="Region name, e.g. global, asia")
    parser.add_argument("--all", action="store_true", help="Plot all variables and all regions.")
    parser.add_argument("--list", action="store_true", help="List variables and regions, then exit.")
    parser.add_argument("--show", action="store_true", help="Show plot interactively.")

    parser.add_argument(
        "--indir",
        default="/gpfsm/dnb06/projects/p271/aqcgan_products/v2_2_0/leadmean_global_and_regional_timeseries",
    )

    parser.add_argument(
        "--scale-file",
        default="/gpfsm/dnb06/projects/p271/aqcgan_products/v2_2_0/plot_metadata/leadmean_global_and_regional_timeseries_scales.npz",
    )

    parser.add_argument("--outdir", default=None)

    args = parser.parse_args()

    indir = Path(args.indir)
    scale_file = Path(args.scale_file)
    outdir = Path(args.outdir) if args.outdir else indir / "plots"
    outdir.mkdir(parents=True, exist_ok=True)

    if args.list:
        print_options()
        return

    if args.all:
        for region in REGIONS:
            for variable in VARIABLES:
                plot_one(variable, region, indir, outdir, scale_file, show=False)
        print(f"\nDone. Plots saved in: {outdir}")
        return

    variable = args.variable
    region = args.region

    if variable is None:
        print_variable_menu()
        variable = choose_from_list(VARIABLES, "Variable: ")

    if region is None:
        print_region_menu()
        region = choose_from_list(list(REGIONS.keys()), "Region: ")

    if variable not in VARIABLES:
        raise ValueError(f"Unknown variable: {variable}")

    if region not in REGIONS:
        raise ValueError(f"Unknown region: {region}")

    plot_one(variable, region, indir, outdir, scale_file, show=args.show)


if __name__ == "__main__":
    main()